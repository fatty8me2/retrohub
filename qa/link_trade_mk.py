#!/usr/bin/env python3
"""Generates the scripted-input files used by qa\\link_trade_*.ps1 (retrorun RETRORUN_INPUT_SCRIPT format: 'frame:BUTTONS', a mask holds until
the next line; 'frame:@shot <file>' takes a screenshot; '{OUT}' is replaced by the PowerShell driver).

usage: link_trade_mk.py <outdir>            (writes <outdir>\\link_trade_<game>_p0.txt / _p1.txt)

Program language (space separated):  wN idle N frames | BTN tap (6 down, 10 up) | BTN*N hold N frames | @name screenshot {OUT}\\name.png
Peer 1 starts its first counter interaction 40 frames after peer 0 (the link handshake needs the two Game Boys out of phase)."""
import os, sys

def build(prog):
    f, lines = 0, []
    for tok in prog.split():
        if tok[0] == 'w' and tok[1:].isdigit():
            f += int(tok[1:]); continue
        if tok[0] == '@':
            lines.append(f"{f}:@shot {{OUT}}\\{tok[1:]}.png"); continue
        hold = None
        if '*' in tok:
            tok, h = tok.split('*'); hold = int(h)
        d = hold or 6
        lines.append(f"{f}:{tok}"); lines.append(f"{f+d}:-")
        f += d + (4 if hold else 10)
    return f, lines

# Gen 1 (Red/Blue/Yellow): boot -> CONTINUE (save is parked in front of the Cable Club receptionist, Pokedex event set) -> receptionist -> TRADE CENTER
# -> walk to the table -> choose own Pokemon -> TRADE -> confirm -> trade animation -> list again ("Trade completed!").
def gen1(off, turn):
    return ("w400 START*20 w300 START*20 w300 A*20 w200 A*20 w300 A*20 w400 @continued UP*8 w%d @counter "
            "A*10 w100 @welcome A*10 w100 A*10 w100 A*10 w300 @saveprompt A*10 w300 A*10 w300 @linkmenu A*10 w600 @tradeservice %s*6 w20 w150 A*10 w600 @partnerlist "
            "A*10 w100 RIGHT*6 w40 @tradebutton A*10 w100 A*10 w100 A*10 w300 @waitingpartner A*10 w150 A*10 w150 A*10 w200 @animation A*10 w300 A*10 w300 A*10 w300 A*10 w300 A*10 w300 w600 w600 @done w60") % (off, turn)

PROGRAMS = {
    'red': (gen1(20, 'RIGHT'), gen1(60, 'LEFT')),
}

if __name__ == '__main__':
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    for game, (p0, p1) in PROGRAMS.items():
        for i, prog in enumerate((p0, p1)):
            n, lines = build(prog)
            path = os.path.join(out, f"link_trade_{game}_p{i}.txt")
            with open(path, 'w', newline='\n') as fh:
                fh.write(f"# frames {n + 60}\n# generated by qa\\link_trade_mk.py; do not edit\n" + "\n".join(lines) + "\n")
            print(path, n)
