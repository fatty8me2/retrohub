"""Turn the RDRAM captures of real matches (N64RUN_QA_RESULT_DUMP) into src/n64run/test_match_result_fixtures.h.

Each capture is 0x640 bytes of RDRAM starting at physical 0xA4AD0 (the scene block, the VS block, the sudden-death block), big-endian N64 order.
Usage: python3 qa/gen_match_result_fixtures.py <outdir with the .bin files> <output header>
"""
import os
import sys

src, out = sys.argv[1], sys.argv[2]
FIX = [
    ('kRemixStock1v1', 'remix_stock.1.bin', 'Smash Remix 2.0.0, --match stage=6;stocks=1;p0=0:0;p1=8:0 with random input: stock rules, Mario fell, Kirby won (results screen, scene 0x18)'),
    ('kVanillaStock1v1', 'van_stock.1.bin', 'Super Smash Bros. (USA), the same --match: the vanilla ROM lays the blocks out the same way'),
    ('kRemixTime1v1', 'remix_time2.1.bin', 'Smash Remix 2.0.0, --match rules=1;time=1 (a one minute timed match): the blocks keep place 0 for everybody, the results screen ranks by KOs - falls'),
    ('kRemixCpuMatch', 'remix_stock.2.bin', 'Smash Remix 2.0.0, a match started from the menus by the random input: time rules, teams, one human (Samus) against one CPU (Peach) who KO\'d her once'),
]
lines = []
lines.append('#pragma once')
lines.append('// GENERATED by qa/gen_match_result_fixtures.py from RDRAM captures of real matches (N64RUN_QA_RESULT_DUMP). Do not edit by hand.')
lines.append('// Each string is 0x640 bytes of RDRAM from physical 0xA4AD0 (scene block, VS block, sudden-death block), big-endian N64 order, as hex.')
lines.append('')
for name, fn, why in FIX:
    data = open(os.path.join(src, fn), 'rb').read()
    assert len(data) == 0x640, (fn, len(data))
    h = data.hex()
    lines.append('// ' + why)
    lines.append('static const char* const %s =' % name)
    for i in range(0, len(h), 96):
        lines.append('    "%s"' % h[i:i + 96])
    lines[-1] += ';'
    lines.append('')
open(out, 'w', newline='\n').write('\n'.join(lines))
print('wrote', out)
