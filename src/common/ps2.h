#pragma once
/* PlayStation 2 disc identification (pure, no hub dependencies): ISO9660 SYSTEM.CNF -> disc serial -> title.
 * Readers for plain .iso (2048-byte sectors), raw .bin/.cue (2352), .cso (CISO v1) and in-memory buffers (archive probes).
 * .chd (CD and DVD) is read through libchdr (disc_id.h). See docs/PS2.md. */

#include <cstddef>
#include <cstdint>
#include <functional>
#include <memory>
#include <string>

#include "disc_id.h"

namespace hub { namespace ps2 {

using namespace hub::disc;   // normalize_serial, serial_from_filename, Cnf, parse_system_cnf, SectorFn, Disc ... (shared with PS1)

extern const char* const kDb[];   // "SERIAL|Title", sorted (ps2_db.cpp, generated by scripts/gen_ps2_db.js)
extern const size_t kDbCount;

/* Title from the bundled database, "" if unknown. */
std::string title_for(const std::string& serial);

struct Ident {
    std::string serial;   // "SLUS-20946" ("" when only the file name was usable)
    std::string title;
    bool ps1 = false;     // a PlayStation 1 disc (BOOT = ...): not ours
};
/* .iso .bin .cso .cue .chd. false when the file is not a PS2 game (a PS1 disc is false with ident->ps1 = true). */
bool identify_file(const std::string& path_utf8, Ident* out);
/* Identity from an in-memory image prefix (archive members). */
bool identify_buffer(std::shared_ptr<std::string> data, Ident* out);

/* A stored (uncompressed) CHD at [base, base+size) of a file, e.g. a stored zip entry; falls back to the entry name's serial. */
bool identify_chd_slice(const std::string& path_utf8, uint64_t base, uint64_t size, const std::string& entry_name, Ident* out);

/* Region wanted by a Redump/No-Intro style name: "(USA)", "(Europe)", "(Japan)", "[NTSC-U]", "[PAL]" -> 'U' 'E' 'J'; 0 if none. */
char region_from_name(const std::string& name);
/* Serial of the PS2 game whose database title equals this name (archive / file name, extension and "(...)" "[...]" groups ignored, case and
 * punctuation insensitive) and whose serial prefix fits the region in the name. "" when no title matches. *ambiguous is set when more than one
 * serial still fits (the lowest serial is returned). */
std::string serial_for_name(const std::string& name, bool* ambiguous = nullptr);

/* Library key: "ps2:<serial lower>" or "ps2:file-<stem>". */
std::string key_for(const std::string& serial, const std::string& file_stem_key);

}} // namespace hub::ps2
