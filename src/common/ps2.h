#pragma once
/* PlayStation 2 disc identification (pure, no hub dependencies): ISO9660 SYSTEM.CNF -> disc serial -> title.
 * Readers for plain .iso (2048-byte sectors), raw .bin/.cue (2352), .cso (CISO v1) and in-memory buffers (archive probes).
 * .chd is not decoded: those games are identified by a serial in the file name. See docs/PS2.md. */

#include <cstddef>
#include <cstdint>
#include <functional>
#include <memory>
#include <string>

namespace hub { namespace ps2 {

extern const char* const kDb[];   // "SERIAL|Title", sorted (ps2_db.cpp, generated by scripts/gen_ps2_db.js)
extern const size_t kDbCount;

/* "SLUS_209.46" / "slus-20946" / "SLUS20946" -> "SLUS-20946"; "" when it is not a serial. */
std::string normalize_serial(const std::string& s);
/* First serial-looking token in a file name ("GTA SA [SLUS-20946].chd"), "" if none. */
std::string serial_from_filename(const std::string& name);
/* Title from the bundled database, "" if unknown. */
std::string title_for(const std::string& serial);

enum class Cnf { None, Ps2, Ps1 };
/* SYSTEM.CNF text: BOOT2 = cdrom0:\SLUS_209.46;1 (PS2) or BOOT = cdrom:\SCUS_941.63;1 (PS1). */
Cnf parse_system_cnf(const std::string& text, std::string* serial);

/* Reads one 2048-byte user-data sector. */
using SectorFn = std::function<bool(uint32_t lba, uint8_t* out2048)>;
/* ISO9660: the root directory's SYSTEM.CNF. */
bool read_system_cnf(const SectorFn& read, std::string* text);
/* Sector reader over a buffer holding the start of a 2048-byte-sector image. */
SectorFn buffer_reader(std::shared_ptr<std::string> data);

/* A disc image on disk. kind: iso, raw (2352-byte sectors, .bin), cso. */
class Disc {
  public:
    Disc();
    ~Disc();
    bool open(const std::string& path_utf8);     // by extension (.iso .bin .cso); false if unreadable or not that format
    SectorFn reader();
  private:
    struct Impl;
    std::shared_ptr<Impl> p_;
};

/* First FILE "name" of a .cue sheet, "" if none. */
std::string cue_first_file(const std::string& cue_text);

struct Ident {
    std::string serial;   // "SLUS-20946" ("" when only the file name was usable)
    std::string title;
    bool ps1 = false;     // a PlayStation 1 disc (BOOT = ...): not ours
};
/* .iso .bin .cso .cue .chd. false when the file is not a PS2 game (a PS1 disc is false with ident->ps1 = true). */
bool identify_file(const std::string& path_utf8, Ident* out);
/* Identity from an in-memory image prefix (archive members). */
bool identify_buffer(std::shared_ptr<std::string> data, Ident* out);

/* Library key: "ps2:<serial lower>" or "ps2:file-<stem>". */
std::string key_for(const std::string& serial, const std::string& file_stem_key);

}} // namespace hub::ps2
