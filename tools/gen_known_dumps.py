#!/usr/bin/env python3
"""Build data/known_dumps.bin: RetroHub's compact list of known-good cartridge dumps.

Source: the No-Intro .dat files that libretro-database mirrors (https://github.com/libretro/libretro-database, metadat/no-intro).
libretro-database is licensed CC-BY-SA-4.0 (https://creativecommons.org/licenses/by-sa/4.0/); the No-Intro data itself is
credited to the No-Intro project (https://no-intro.org). The output is a derived work and keeps that license (see docs/VERIFY.md).

Only metadata is fetched: CRC32, size and the canonical title of each entry. Never a ROM.

Systems: NES, SNES, N64, GB, GBC, GBA, NDS. Disc systems (PS1, PS2, GC, Wii U, 3DS) are out of scope.

What is kept per system (so the app can hash a file the way the list was made):
  nes   .unh   headerless PRG+CHR (the app hashes without the 16-byte iNES header)
  snes  .sfc   headerless (the app strips a 512-byte copier header)
  n64   .z64   big-endian "z64" order (the app converts .v64 / .n64 dumps before hashing)
  gb gbc gba nds   the plain file

File layout: one ASCII header line ("RHKD1 ...\\n"), then a zlib stream of tab-separated text:
    @<system short name>\\t<entry count>
    <crc32 hex, 8 digits>\\t<size in bytes>\\t<title>
Lines starting with '#' are comments.

Usage:
    python tools/gen_known_dumps.py                      # fetch the .dat files, write data/known_dumps.bin
    python tools/gen_known_dumps.py --from-dir DIR       # use already downloaded .dat files (offline)
    python tools/gen_known_dumps.py --selftest           # parser self test, no network
"""
import argparse
import datetime
import os
import re
import sys
import urllib.parse
import urllib.request
import zlib

BASE = "https://raw.githubusercontent.com/libretro/libretro-database/master/metadat/no-intro/"
# system short name -> (dat file name, accepted rom extensions)
SYSTEMS = [
    ("nes", "Nintendo - Nintendo Entertainment System", {"unh"}),
    ("snes", "Nintendo - Super Nintendo Entertainment System", {"sfc"}),
    ("n64", "Nintendo - Nintendo 64", {"z64"}),
    ("gb", "Nintendo - Game Boy", {"gb"}),
    ("gbc", "Nintendo - Game Boy Color", {"gbc"}),
    ("gba", "Nintendo - Game Boy Advance", {"gba"}),
    ("nds", "Nintendo - Nintendo DS", {"nds"}),
]
LICENSE_LINES = [
    "# RetroHub known-good cartridge dumps (CRC32 + size + title only; no ROM data).",
    "# Derived from the No-Intro .dat files mirrored by libretro-database (github.com/libretro/libretro-database, metadat/no-intro).",
    "# libretro-database is licensed CC-BY-SA-4.0: https://creativecommons.org/licenses/by-sa/4.0/ . No-Intro: https://no-intro.org .",
    "# This file is a derived work under the same license (attribution + share-alike). Generated by tools/gen_known_dumps.py.",
]

ROM_RE = re.compile(r'rom \( name "(.*)" size (\d+) crc ([0-9A-Fa-f]{1,8})')
GAME_NAME_RE = re.compile(r'^\tname "(.*)"\s*$', re.M)
VERSION_RE = re.compile(r'^\tversion "(.*)"\s*$', re.M)


def parse_dat(text, exts):
    """clrmamepro text -> sorted list of (crc, size, title), one per (crc, size). Pure; see --selftest."""
    out = {}
    for block in re.split(r'\ngame \(\n', text)[1:]:
        m = GAME_NAME_RE.search(block)
        if not m:
            continue
        title = m.group(1).replace("\t", " ").strip()
        for r in ROM_RE.finditer(block):
            name, size, crc = r.group(1), int(r.group(2)), int(r.group(3), 16)
            ext = name.rsplit(".", 1)[-1].lower() if "." in name else ""
            if ext not in exts:
                continue
            out.setdefault((crc, size), title)
    return sorted(((c, s, t) for (c, s), t in out.items()), key=lambda x: (x[2].lower(), x[0]))


def dat_version(text):
    m = VERSION_RE.search(text[:600])
    return m.group(1) if m else "?"


def build(per_system, versions):
    lines = list(LICENSE_LINES)
    lines.append("# source dat versions: " + ", ".join("%s=%s" % (k, versions[k]) for k, _ in per_system))
    for sysname, rows in per_system:
        lines.append("@%s\t%d" % (sysname, len(rows)))
        for c, s, t in rows:
            lines.append("%08X\t%d\t%s" % (c, s, t))
    raw = ("\n".join(lines) + "\n").encode("utf-8")
    vers = ",".join(sorted(set(versions.values())))
    header = "RHKD1 CC-BY-SA-4.0 libretro-database metadat/no-intro dat=%s generated=%s\n" % (vers, datetime.date.today().isoformat())
    return header.encode("ascii") + zlib.compress(raw, 9), len(raw)


def fetch(name):
    url = BASE + urllib.parse.quote(name + ".dat")
    req = urllib.request.Request(url, headers={"User-Agent": "RetroHub-known-dumps/1"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8", errors="replace")


def selftest():
    sample = (
        'clrmamepro (\n\tname "x"\n\tversion "2026.01.01"\n)\n\n'
        'game (\n\tname "Game A (USA)"\n\trom ( name "Game A (USA).nes" size 40976 crc 11223344 md5 AA sha1 BB )\n)\n'
        'game (\n\tname "Game A (USA)"\n\trom ( name "Game A (USA).unh" size 40960 crc 0A0B0C0D md5 AA sha1 BB )\n)\n'
        'game (\n\tname "Odd \\"Name\\" (Japan)"\n\trom ( name "Odd (Japan).unh" size 100 crc FF md5 AA sha1 BB )\n)\n'
    )
    rows = parse_dat(sample, {"unh"})
    assert rows == [(0x0A0B0C0D, 40960, "Game A (USA)"), (0xFF, 100, 'Odd \\"Name\\" (Japan)')], rows
    assert dat_version(sample) == "2026.01.01"
    blob, _ = build([("nes", rows)], {"nes": "2026.01.01"})
    head, _, body = blob.partition(b"\n")
    assert head.startswith(b"RHKD1 CC-BY-SA-4.0")
    text = zlib.decompress(body).decode("utf-8")
    assert "@nes\t2" in text and "0A0B0C0D\t40960\tGame A (USA)" in text
    assert "000000FF\t100\t" in text
    print("gen_known_dumps selftest OK")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--from-dir", help="read the .dat files from this folder instead of downloading")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", "known_dumps.bin"))
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        selftest()
        return 0
    per_system, versions = [], {}
    for sysname, datname, exts in SYSTEMS:
        if a.from_dir:
            with open(os.path.join(a.from_dir, datname + ".dat"), encoding="utf-8", errors="replace") as f:
                text = f.read()
        else:
            print("fetching", datname)
            text = fetch(datname)
        rows = parse_dat(text, exts)
        if len(rows) < 100:
            print("error: only %d entries for %s; refusing to write a broken list" % (len(rows), sysname), file=sys.stderr)
            return 1
        versions[sysname] = dat_version(text)
        per_system.append((sysname, rows))
        print("  %-5s %6d entries (dat %s)" % (sysname, len(rows), versions[sysname]))
    blob, raw_len = build(per_system, versions)
    with open(a.out, "wb") as f:
        f.write(blob)
    print("wrote %s: %d bytes (%d bytes of text before compression)" % (os.path.normpath(a.out), len(blob), raw_len))
    return 0


if __name__ == "__main__":
    sys.exit(main())
