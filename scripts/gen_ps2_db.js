// Generates src/common/ps2_db.cpp (compact serial -> title table) from PCSX2's GameIndex.yaml.
// Usage: node scripts/gen_ps2_db.js <GameIndex.yaml> <out ps2_db.cpp>
// Source: github.com/PCSX2/pcsx2 bin/resources/GameIndex.yaml (GPL-3.0; serials/titles come from Redump, psxdatacenter, serialstation).
const fs = require('fs');
const [, , inp, out] = process.argv;
const lines = fs.readFileSync(inp, 'utf8').split(/\r?\n/);
const rows = new Map();
let cur = null;
const unq = (s) => s.trim().replace(/^"(.*)"$/, '$1').replace(/\\"/g, '"');
for (const ln of lines) {
  let m = /^([A-Z]{4}-\d{5}):\s*$/.exec(ln);
  if (m) { cur = { serial: m[1], name: '', en: '' }; rows.set(m[1], cur); continue; }
  if (!cur) continue;
  if ((m = /^  name:\s*(.*)$/.exec(ln))) cur.name = unq(m[1]);
  else if ((m = /^  name-en:\s*(.*)$/.exec(ln))) cur.en = unq(m[1]);
}
const ascii = (s) => /^[\x20-\x7e]+$/.test(s);
const items = [];
for (const r of rows.values()) {
  let t = r.en && ascii(r.en) ? r.en : (ascii(r.name) ? r.name : '');
  t = t.replace(/\|/g, '-').replace(/\\/g, '/');
  if (t) items.push(r.serial + '|' + t);
}
items.sort();
let o = '// GENERATED by scripts/gen_ps2_db.js from PCSX2 GameIndex.yaml (v2.8.2). Do not edit.\n';
o += '// Format: "SERIAL|Title" sorted by serial; non-Latin-only titles are left out (those games show the file name).\n';
o += '#include "ps2.h"\n\nnamespace hub { namespace ps2 {\n\nconst char* const kDb[] = {\n';
for (const it of items) o += '    "' + it.replace(/"/g, '\\"') + '",\n';
o += '};\nconst size_t kDbCount = sizeof(kDb) / sizeof(kDb[0]);\n\n}} // namespace hub::ps2\n';
fs.writeFileSync(out, o);
console.log(items.length + ' entries');
